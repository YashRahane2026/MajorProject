/**
 * Helper to query official statistics safely by jurisdiction and optional year.
 */
export function getOfficialStatsByJurisdiction(
  jurisdictionId: 'nagpur_city' | 'nagpur_railway',
  year?: number
): OfficialStatisticRecord[] {
  return VERIFIED_OFFICIAL_STATISTICS.filter(
    (r) => r.jurisdiction_id === jurisdictionId && (year === undefined || r.year === year)
  );
}
